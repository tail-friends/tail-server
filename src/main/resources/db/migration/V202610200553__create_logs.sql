-- 기록 6종(FEED, SHED, WEIGHT, CLEAN, ENV, NOTE)을 한 테이블에 둔다. 종류별 컬럼은 해당 종류에서만 값이 있다.
CREATE TABLE logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id     BIGINT        NOT NULL REFERENCES animals (id) ON DELETE CASCADE,
    user_id       BIGINT        NOT NULL REFERENCES users (id),
    client_id     UUID,
    type          VARCHAR(10)   NOT NULL,
    log_date      DATE          NOT NULL,
    memo          VARCHAR(200),
    food          VARCHAR(40),
    food_count    INTEGER,
    refused       BOOLEAN,
    dusted        BOOLEAN,
    shed_stage    VARCHAR(10),
    shed_complete BOOLEAN,
    weight_g      NUMERIC(7, 1) CHECK (weight_g > 0),
    clean_full    BOOLEAN,
    stool         VARCHAR(10),
    hot_c         NUMERIC(4, 1),
    cool_c        NUMERIC(4, 1),
    humidity      INTEGER,
    batch_id      UUID,
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_logs_user_id_client_id UNIQUE (user_id, client_id)
);

CREATE INDEX idx_logs_animal_id_log_date ON logs (animal_id, log_date DESC);
CREATE INDEX idx_logs_animal_id_type_log_date ON logs (animal_id, type, log_date DESC);
