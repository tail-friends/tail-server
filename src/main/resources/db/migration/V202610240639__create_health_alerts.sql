CREATE TABLE health_alerts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id  BIGINT        NOT NULL REFERENCES animals (id) ON DELETE CASCADE,
    type       VARCHAR(30)   NOT NULL,
    message    VARCHAR(100)  NOT NULL,
    status     VARCHAR(15)   NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ   NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_health_alerts_animal_id ON health_alerts (animal_id);

-- 같은 개체·같은 종류의 열린(OPEN) 경고는 하나만 둔다
CREATE UNIQUE INDEX uk_health_alerts_open_animal_id_type ON health_alerts (animal_id, type) WHERE status = 'OPEN';
