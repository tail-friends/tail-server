-- 합사 보기(F-29). 한 사육장 화면에 함께 띄울 개체. 화면에서만 함께 보이고, 한 개체를 여러 사육장에 넣을 수 있다.
-- 설정할 때 통째로 바꾼다. id 순서가 저장한 순서다. 사육장이나 개체를 지우면 함께 지워진다.
CREATE TABLE enclosure_animals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enclosure_id BIGINT      NOT NULL REFERENCES enclosures (id) ON DELETE CASCADE,
    animal_id    BIGINT      NOT NULL REFERENCES animals (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_enclosure_animals_enclosure_animal UNIQUE (enclosure_id, animal_id)
);

CREATE INDEX idx_enclosure_animals_animal_id ON enclosure_animals (animal_id);
