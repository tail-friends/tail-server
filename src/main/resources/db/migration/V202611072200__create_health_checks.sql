-- 사진 건강 체크 결과 (F-33). items는 [{ "key", "result", "note" }] 배열이다.
-- 사진이 지워져도 결과는 남긴다(photo_id만 비운다).
CREATE TABLE health_checks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id   BIGINT       NOT NULL REFERENCES animals (id) ON DELETE CASCADE,
    photo_id    BIGINT       REFERENCES photos (id) ON DELETE SET NULL,
    items       JSONB        NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_health_checks_animal_id_id ON health_checks (animal_id, id DESC);
CREATE INDEX idx_health_checks_photo_id ON health_checks (photo_id);
