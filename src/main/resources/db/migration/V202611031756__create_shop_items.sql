-- 케어 포인트 상점 아이템. 관리자 API로 넣고, 지우지 않고 판매를 중지한다(on_sale = false).
CREATE TABLE shop_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(30)  NOT NULL,
    category     VARCHAR(12)  NOT NULL,
    price        INT          NOT NULL CHECK (price BETWEEN 1 AND 100000),
    image_url    VARCHAR(500) NOT NULL,
    render_style VARCHAR(20)  NOT NULL DEFAULT 'ILLUSTRATION_2D',
    on_sale      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL
);

-- 산 아이템. 같은 아이템은 한 번만 산다. 구매한 때는 created_at이다.
CREATE TABLE user_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    item_id    BIGINT      NOT NULL REFERENCES shop_items (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_user_items_user_item UNIQUE (user_id, item_id)
);

CREATE INDEX idx_user_items_item_id ON user_items (item_id);
