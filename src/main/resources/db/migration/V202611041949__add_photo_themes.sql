-- 사진 테마(F-27). 사진을 지워도 테마는 남는다
ALTER TABLE enclosures
    ADD COLUMN photo_id   BIGINT REFERENCES photos (id) ON DELETE SET NULL,
    ADD COLUMN floor_color VARCHAR(7),
    ADD COLUMN wall_color  VARCHAR(7),
    ADD CONSTRAINT ck_enclosures_photo_colors
        CHECK ((background_type = 'PHOTO') = (floor_color IS NOT NULL AND wall_color IS NOT NULL));
CREATE INDEX idx_enclosures_photo_id ON enclosures (photo_id);

-- 사진에서 읽은 배경 장식. 상점 아이템을 놓는 enclosure_decorations와 다르다
CREATE TABLE enclosure_objects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enclosure_id  BIGINT        NOT NULL REFERENCES enclosures (id) ON DELETE CASCADE,
    type          VARCHAR(12)   NOT NULL,
    x             NUMERIC(4, 3) NOT NULL CHECK (x BETWEEN 0 AND 1),
    y             NUMERIC(4, 3) NOT NULL CHECK (y BETWEEN 0 AND 1),
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_enclosure_objects_enclosure_id ON enclosure_objects (enclosure_id);

-- 평소 사육장이 사진 테마면 그 사육장. 테마를 지우면 NULL이 되어 종의 기본 테마로 돌아간다
ALTER TABLE animals
    ADD COLUMN enclosure_id BIGINT REFERENCES enclosures (id) ON DELETE SET NULL,
    ADD CONSTRAINT ck_animals_home_or_enclosure CHECK (home IS NULL OR enclosure_id IS NULL);
CREATE INDEX idx_animals_enclosure_id ON animals (enclosure_id);
