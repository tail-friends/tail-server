-- 사육장. 지금은 기본 테마(BUILT_IN)만 있다. 사진 테마(PHOTO) 컬럼은 사진 테마를 만들 때 추가한다.
-- 기본 테마 사육장은 사용자마다 테마 하나에 하나다. 사육장 목록을 처음 볼 때 5개를 만든다.
CREATE TABLE enclosures (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    background_type VARCHAR(10) NOT NULL,
    theme           VARCHAR(10),
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_enclosures_user_theme UNIQUE (user_id, theme),
    CONSTRAINT ck_enclosures_built_in_theme CHECK ((background_type = 'BUILT_IN') = (theme IS NOT NULL))
);

-- 사육장에 놓은 장식. 배치를 저장할 때 통째로 바꾼다. id 순서가 그리는 순서다.
CREATE TABLE enclosure_decorations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enclosure_id BIGINT       NOT NULL REFERENCES enclosures (id) ON DELETE CASCADE,
    item_id      BIGINT       NOT NULL REFERENCES shop_items (id),
    x            NUMERIC(4, 3) NOT NULL CHECK (x BETWEEN 0 AND 1),
    y            NUMERIC(4, 3) NOT NULL CHECK (y BETWEEN 0 AND 1),
    flip         BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_enclosure_decorations_enclosure_id ON enclosure_decorations (enclosure_id);
CREATE INDEX idx_enclosure_decorations_item_id ON enclosure_decorations (item_id);
