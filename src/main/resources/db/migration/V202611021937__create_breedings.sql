-- 번식 기록. 부모가 외부 개체면 이름만 저장한다. 내 개체여도 이름을 함께 저장해 개체를 지워도 이름이 남는다.
CREATE TABLE breedings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    male_id     BIGINT      REFERENCES animals (id) ON DELETE SET NULL,
    male_name   VARCHAR(30) NOT NULL,
    female_id   BIGINT      REFERENCES animals (id) ON DELETE SET NULL,
    female_name VARCHAR(30) NOT NULL,
    paired_date DATE        NOT NULL,
    status      VARCHAR(12) NOT NULL DEFAULT 'PAIRED',
    memo        VARCHAR(200),
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_breedings_user_id_paired_date ON breedings (user_id, paired_date DESC);

-- 산란 기록. 번식 기록을 수정할 때 통째로 바꾼다.
CREATE TABLE clutches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breeding_id         BIGINT       NOT NULL REFERENCES breedings (id) ON DELETE CASCADE,
    laid_date           DATE         NOT NULL,
    egg_count           INT          NOT NULL CHECK (egg_count BETWEEN 1 AND 99),
    incubation_temp     NUMERIC(4, 1),
    expected_hatch_date DATE,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_clutches_breeding_id ON clutches (breeding_id);

-- 해칭 개체 등록으로 만든 개체. 번식 기록을 지워도 개체는 남는다.
ALTER TABLE animals ADD COLUMN breeding_id BIGINT REFERENCES breedings (id) ON DELETE SET NULL;

CREATE INDEX idx_animals_breeding_id ON animals (breeding_id);
