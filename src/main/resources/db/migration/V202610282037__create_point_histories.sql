-- 케어 포인트 적립·사용 내역. 잔액은 users.points다.
-- 같은 개체·같은 종류는 기록한 날(KST, earned_date) 하루 1번만 적립한다. 사용(PURCHASE)은 earned_date가 NULL이다.
-- 개체나 기록을 지워도 내역은 남긴다(포인트를 빼지 않으므로).
CREATE TABLE point_histories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    animal_id   BIGINT      REFERENCES animals (id) ON DELETE SET NULL,
    log_id      BIGINT      REFERENCES logs (id) ON DELETE SET NULL,
    amount      INT         NOT NULL,
    reason      VARCHAR(20) NOT NULL,
    earned_date DATE,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_point_histories_user_id_id ON point_histories (user_id, id DESC);
CREATE UNIQUE INDEX uk_point_histories_animal_reason_date ON point_histories (animal_id, reason, earned_date);
